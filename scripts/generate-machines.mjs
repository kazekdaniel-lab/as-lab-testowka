async function main() {
  await mkdir(OUT, { recursive: true });

  let count = 0;
  for (const m of machines) {
    const fm = {
      name: m.name,
      shortName: m.shortName,
      model: m.model,
      tagline: m.tagline,
      description: m.description,
      category: m.category,
      categoryPath: m.categoryPath,
      industries: m.industries,
      norms: m.norms || [],
      specs: m.specs || [],
      image: m.image,
      imageAlt: m.imageAlt,
      gallery: m.gallery || [],
      applications: m.applications || [],
      features: m.features || [],
      keywords: m.keywords || [],
      featured: m.featured ?? false,
      order: m.order,
    };

    // Build YAML frontmatter manually for cleaner output
    const yaml = Object.entries(fm)
      .filter(([, v]) => v !== undefined)
      .map(([k, v]) => {
        if (v === undefined || v === null) return null;
        if (typeof v === 'boolean' || typeof v === 'number') return `${k}: ${v}`;
        if (Array.isArray(v)) {
          if (v.length === 0) return `${k}: []`;
          if (typeof v[0] === 'object') {
            return `${k}:\n${v.map((it) =>
              `  - label: "${it.label.replace(/"/g, '\\"')}"\n    value: "${it.value.replace(/"/g, '\\"')}"`
            ).join('\n')}`;
          }
          return `${k}:\n${v.map((x) => `  - "${String(x).replace(/"/g, '\\"')}"`).join('\n')}`;
        }
        return `${k}: "${String(v).replace(/"/g, '\\"').replace(/\n/g, ' ')}"`;
      })
      .filter(Boolean)
      .join('\n');

    const body = `
## Opis

${m.description}

${m.applications && m.applications.length > 0 ? `## Zastosowania

${m.applications.map((a) => `- ${a}`).join('\n')}
` : ''}

${m.features && m.features.length > 0 ? `## Cechy techniczne

${m.features.map((f) => `- ${f}`).join('\n')}
` : ''}

${m.norms && m.norms.length > 0 ? `## Zgodność z normami

${m.norms.map((n) => `- ${n}`).join('\n')}
` : ''}
`.trim();

    const content = `---\n${yaml}\n---\n\n${body}\n`;
    await writeFile(join(OUT, `${m.slug}.md`), content);
    count++;
  }

  console.log(`✓ Wygenerowano ${count} plików maszyn do ${OUT}`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
